## Elementor-ready support

The theme includes support for Elementor integration and page-template scaffolding so the storefront can be refined and edited visually in Elementor Pro without breaking the shared theme styling.

## How to use

1. Copy `noah-theme` into `wp-content/themes/`
2. Activate the theme in Appearance > Themes
3. Install Elementor Pro
4. Go to Appearance > Noah Theme Settings and click Run Demo Import
5. Adjust brand colors and contact values in Appearance > Customize

## Notes

This version is intended to provide the full Noah storefront architecture and excellent visual consistency for the repository’s mockups. The final phase for true pixel-perfect matching to every screenshot should be done in Elementor, using these templates as the global structure and design system foundation.

This keeps the theme compatible with WordPress 7+ and designed for easy editing across the entire storefront.
